void showSplashScreen() {
    display.clearDisplay();
    display.drawBitmap(0, 0, logo, 128, 64, SSD1306_WHITE);
    display.display();
    delay(4000);
}

void setupMenu() {
    pinMode(JOY_UP, INPUT_PULLUP);
    pinMode(JOY_DOWN, INPUT_PULLUP);
    pinMode(JOY_LEFT, INPUT_PULLUP);
    pinMode(JOY_RIGHT, INPUT_PULLUP);
    pinMode(JOY_CENTER, INPUT_PULLUP);
    pinMode(BACK_BUTTON, INPUT_PULLUP);
    pinMode(SD_CS, OUTPUT);

    // OLED setup
    if (!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
        Serial.println(F("SSD1315 OLED init failed!"));
        while (1);
    }

    showSplashScreen();

    display.clearDisplay();
    display.setTextSize(1);
    display.setTextColor(SSD1306_WHITE);
    display.display();

    // SD card init
    SPI2.begin(SD_SCLK, SD_MISO, SD_MOSI, SD_CS);
    if (!SD.begin(SD_CS, SPI2)) {
        Serial.println("SD Card not found.");
    } else {
        Serial.println("SD Card initialized.");
    }
}

void showMainMenu() {
    display.clearDisplay();
    display.setCursor(0, 0);
    display.println("Select an option:");
    display.setCursor(10, 15);
    display.println(selectedOption == 0 ? "> Joystick Test" : "  Joystick Test");
    display.setCursor(10, 30);
    display.println(selectedOption == 1 ? "> List SD Files" : "  List SD Files");
    display.setCursor(10, 45);
    display.println(selectedOption == 2 ? "> Software Version" : "  Software Version");
    display.display();

    if (digitalRead(JOY_DOWN) == LOW) {
        selectedOption = (selectedOption + 1) % 3;
        delay(200);
    }
    if (digitalRead(JOY_UP) == LOW) {
        selectedOption = (selectedOption + 2) % 3;  // Wrap around
        delay(200);
    }
    if (digitalRead(JOY_CENTER) == LOW) {
        currentMenu = selectedOption + 1;
        delay(200);
    }
}

void joystickTest() {
    display.clearDisplay();
    display.setCursor(0, 0);
    display.println("Joystick Test:");

    if (digitalRead(JOY_UP) == LOW) display.println("UP");
    if (digitalRead(JOY_DOWN) == LOW) display.println("DOWN");
    if (digitalRead(JOY_LEFT) == LOW) display.println("LEFT");
    if (digitalRead(JOY_RIGHT) == LOW) display.println("RIGHT");
    if (digitalRead(JOY_CENTER) == LOW) display.println("CENTER");

    display.display();

    if (digitalRead(BACK_BUTTON) == LOW) {
        currentMenu = 0;
        delay(300);
    }
}

void printDirectory(File dir) {
    while (true) {
        File entry = dir.openNextFile();
        if (!entry) break;

        if (!entry.isDirectory() && fileCount < 20) {
            sdFiles[fileCount++] = String(entry.name());
        }

        entry.close();
    }
}

void listSDCardFiles() {
    display.clearDisplay();
    display.setCursor(0, 0);

    if (!SD.begin(SD_CS)) {
        display.println("SD not found");
        display.display();
        delay(1000);
        currentMenu = 0;
        return;
    }

    fileCount = 0;
    File root = SD.open("/");
    printDirectory(root);
    root.close();

    for (int i = 0; i < fileCount && i < 5; i++) {
        display.println(sdFiles[i]);
    }
    display.display();

    if (digitalRead(BACK_BUTTON) == LOW) {
        currentMenu = 0;
        delay(300);
    }
}

void showSoftwareVersion() {
    display.clearDisplay();
    display.setCursor(0, 0);
    display.println("Software Version:");
    display.println("v1.0.0");
    display.display();

    if (digitalRead(BACK_BUTTON) == LOW) {
        currentMenu = 0;
        delay(300);
    }
}

void loopMenu() {
    switch (currentMenu) {
        case 0:
            showMainMenu();
            break;
        case 1:
            joystickTest();
            break;
        case 2:
            listSDCardFiles();
            break;
        case 3:
            showSoftwareVersion();
            break;
    }
}